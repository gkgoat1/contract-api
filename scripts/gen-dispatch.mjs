#!/usr/bin/env node
/**
 * Dispatch-file generator: turns a public-service spec (name, address, ABI
 * fragments) into a typed dispatch module under src/core/dispatch/. Services
 * designed for contract-level batched interaction (Multicall3 today; future
 * public services later) are added by appending to dispatch.spec.json and
 * re-running — every smart-wallet context then shares the same dispatch.
 *
 *   node scripts/gen-dispatch.mjs            # regenerate all
 *   node scripts/gen-dispatch.mjs --check    # diff only (CI / golden test)
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { createHash } from "node:crypto";

const ROOT = new URL("..", import.meta.url).pathname;
const spec = JSON.parse(readFileSync(`${ROOT}dispatch.spec.json`, "utf8"));

function tsType(comp) {
  if (comp.type === "address") return "`0x${string}`";
  if (comp.type === "bool") return "boolean";
  if (comp.type === "bytes") return "`0x${string}`";
  if (comp.type === "string") return "string";
  if (/^u?int/.test(comp.type)) return "bigint";
  if (comp.type === "tuple" || comp.type === "tuple[]") {
    const fields = comp.components.map((c) => `${c.name}: ${tsType(c)}`).join("; ");
    return `{ ${fields} }${comp.type.endsWith("[]") ? "[]" : ""}`;
  }
  throw new Error(`gen-dispatch: unsupported ABI type ${comp.type}`);
}

function emitFunction(fn) {
  const inputs = fn.inputs ?? [];
  const outputs = fn.outputs ?? [];
  const argList = inputs.map((i) => `${i.name}: ${tsType(i)}`).join(", ");
  const tupleIn = `{ ${inputs.map((i) => `${i.name}`).join(", ")} }`;
  const ret =
    outputs.length === 0
      ? "void"
      : outputs.length === 1
        ? tsType(outputs[0])
        : `{ ${outputs.map((o) => `${o.name}: ${tsType(o)}`).join("; ")} }`;
  const decodeBody =
    outputs.length === 0
      ? "undefined"
      : `decodeFunctionResult({ abi: ABI, functionName: "${fn.name}", data }) as unknown as ${ret}`;
  return `
  /** ${fn.stateMutability ?? "nonpayable"} — ${fn.name}(${inputs.map((i) => i.type).join(", ")}) */
  ${fn.name}(${argList}) {
    return {
      to: ADDRESS,
      data: encodeFunctionData({ abi: ABI, functionName: "${fn.name}", args: [${inputs.map((i) => i.name).join(", ")}] }),
    } as const;
  },
  decode${fn.name[0].toUpperCase()}${fn.name.slice(1)}(data: \`0x\${string}\`): ${ret} {
    return ${decodeBody};
  },`;
}

function emitService(svc) {
  const abiJson = JSON.stringify(svc.abi, null, 2);
  const hash = createHash("sha256").update(JSON.stringify(svc)).digest("hex").slice(0, 12);
  return `// GENERATED by scripts/gen-dispatch.mjs from dispatch.spec.json (${svc.name}, spec ${hash}).
// Do not edit by hand — re-run the generator. Other public services designed for
// contract-level batched interaction are added to dispatch.spec.json the same way.
import { encodeFunctionData, decodeFunctionResult, type Address, type Hex } from "viem";

export const ADDRESS: Address = ${JSON.stringify(svc.address)};

export const ABI = ${abiJson} as const;

/** Delegatecall-safe: this service is stateless/self-contained, so wallets batch
 *  by delegatecalling it (calls then execute with msg.sender = the wallet — e.g.
 *  wallet.delegate(ADDRESS, multicall3.aggregate3(calls).data)). */
export const DELEGATE_SAFE = ${svc.delegateSafe === true};

/** Typed dispatch for the ${svc.name} public service at ADDRESS. */
export const ${svc.name} = {
${svc.abi.filter((f) => f.type === "function").map(emitFunction).join("\n")}
} as const;
`;
}

const check = process.argv.includes("--check");
let drift = false;
for (const svc of spec.services) {
  const out = emitService(svc);
  const path = `${ROOT}src/core/dispatch/${svc.name}.ts`;
  if (check) {
    let current = null;
    try {
      current = readFileSync(path, "utf8");
    } catch {}
    if (current !== out) {
      console.error(`dispatch drift: ${svc.name}`);
      drift = true;
    }
  } else {
    mkdirSync(`${ROOT}src/core/dispatch`, { recursive: true });
    writeFileSync(path, out);
    console.log(`generated src/core/dispatch/${svc.name}.ts`);
  }
}
process.exit(check && drift ? 1 : 0);
